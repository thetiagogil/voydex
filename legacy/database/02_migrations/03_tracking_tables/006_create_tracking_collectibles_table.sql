-- ============================================================================
-- Table: tracking.collectibles
-- Collectible metadata for tracking milestones.
-- Example types: sticker, cell, diglett, wisp, stake.
-- ============================================================================
CREATE TABLE
    tracking.collectibles (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES reference.version_groups (id),
        game_id INTEGER NULL REFERENCES reference.games (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        collectible_type TEXT NOT NULL,
        total_count INTEGER NULL,
        sprite_url TEXT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Comments
COMMENT ON TABLE tracking.collectibles IS 'Collectible metadata. Linked to tracking items via item_collectible_refs.';
