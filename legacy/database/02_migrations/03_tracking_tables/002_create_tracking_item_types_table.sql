-- ============================================================================
-- Table: tracking.item_types
-- Defines structural behavior of tracking milestones.
-- Examples: story-battle, story-checkpoint, pokemon-milestone, collectible,
--           decision.
-- ============================================================================
CREATE TABLE
    tracking.item_types (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        slug TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW ()
    );

-- Comments
COMMENT ON TABLE tracking.item_types IS 'Structural behavior types for tracking milestones.';