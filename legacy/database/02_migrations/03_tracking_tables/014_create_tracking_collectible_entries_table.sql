-- ============================================================================
-- Table: tracking.collectible_entries
-- One row per actual collectible unit / map entry.
-- Collectible equivalent of reference.pokedex_entries.
-- ============================================================================
CREATE TABLE
    tracking.collectible_entries (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        collectible_id INTEGER NOT NULL REFERENCES tracking.collectibles (id) ON DELETE CASCADE,
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        location_name TEXT NULL,
        sub_location_name TEXT NULL,
        description TEXT NULL,
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (collectible_id, slug),
        UNIQUE (collectible_id, sort_order)
    );

-- Comments
COMMENT ON TABLE tracking.collectible_entries IS 'Individual collectible units within a collectible system. One row per trackable entry.';

COMMENT ON COLUMN tracking.collectible_entries.location_name IS 'Broad area where this entry is found.';

COMMENT ON COLUMN tracking.collectible_entries.sub_location_name IS 'More precise sub-area within the location.';