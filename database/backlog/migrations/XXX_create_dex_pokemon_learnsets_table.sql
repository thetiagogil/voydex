CREATE TABLE
  meta.pokemon_learnsets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id INTEGER NOT NULL REFERENCES meta.pokemon_species (id) ON DELETE CASCADE,
    form_id INTEGER REFERENCES meta.pokemon_forms (id) ON DELETE CASCADE,
    move_id INTEGER NOT NULL REFERENCES meta.moves (id) ON DELETE CASCADE,
    generation_id INTEGER NOT NULL REFERENCES meta.generations (id) ON DELETE CASCADE,
    version_group_id INTEGER REFERENCES meta.version_groups (id) ON DELETE CASCADE,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (species_id, form_id, move_id, generation_id)
  );

CREATE INDEX idx_learnsets_form_gen ON meta.pokemon_learnsets (form_id, generation_id);

CREATE INDEX idx_learnsets_species_gen ON meta.pokemon_learnsets (species_id, generation_id);

CREATE INDEX idx_learnsets_move_gen ON meta.pokemon_learnsets (move_id, generation_id);

CREATE INDEX idx_learnsets_version_group ON meta.pokemon_learnsets (version_group_id);