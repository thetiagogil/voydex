-- ============================================================================
-- Table: reference.item_availability
-- Pokémon-relevant item availability by version group and optional game scope.
-- ============================================================================
CREATE TABLE reference.item_availability (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id integer NOT NULL REFERENCES reference.items (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    version_group_id integer NOT NULL REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    game_id integer,
    availability_method_id integer REFERENCES reference.availability_methods (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    scope_operation text NOT NULL DEFAULT 'add',
    notes text,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT item_availability_id_positive_check CHECK (id > 0),
    CONSTRAINT item_availability_game_scope_fkey FOREIGN KEY (game_id, version_group_id) REFERENCES reference.game_content_scopes (game_id, version_group_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT item_availability_scope_operation_check CHECK (scope_operation IN ('add', 'override', 'remove')),
    CONSTRAINT item_availability_notes_length_check CHECK (notes IS NULL OR CHAR_LENGTH(BTRIM(notes)) BETWEEN 1 AND 1000)
);

CREATE UNIQUE INDEX item_availability_vg_method_unique ON reference.item_availability (item_id, version_group_id, (COALESCE(availability_method_id, 0)))
WHERE
    game_id IS NULL;

CREATE UNIQUE INDEX item_availability_game_method_unique ON reference.item_availability (item_id, version_group_id, game_id, (COALESCE(availability_method_id, 0)))
WHERE
    game_id IS NOT NULL;

CREATE INDEX item_availability_scope_lookup_idx ON reference.item_availability (version_group_id, game_id);

CREATE INDEX item_availability_method_lookup_idx ON reference.item_availability (availability_method_id);

COMMENT ON INDEX reference.item_availability_vg_method_unique IS 'Prevents duplicate version-group-wide availability methods for the same item; NULL method is treated as one method bucket.';

COMMENT ON INDEX reference.item_availability_game_method_unique IS 'Prevents duplicate game-specific availability methods for the same item; NULL method is treated as one method bucket.';

COMMENT ON COLUMN reference.item_availability.id IS 'Generated surrogate key for Supabase/client ergonomics; seed files omit id and rely on natural uniqueness constraints.';

COMMENT ON TABLE reference.item_availability IS 'Item availability delta rows for the reduced Pokémon-relevant item catalog.';

COMMENT ON COLUMN reference.item_availability.availability_method_id IS 'Optional because item-specific acquisition method taxonomy is intentionally not fully modeled yet.';

COMMENT ON COLUMN reference.item_availability.game_id IS 'Nullable for version-group-wide availability. When set, the game must be mapped to the same content scope.';

COMMENT ON COLUMN reference.item_availability.scope_operation IS 'Cumulative content-scope operation. add is the normal positive row; override/remove are reserved for source changes that supersede earlier scopes.';
