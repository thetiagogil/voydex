-- ============================================================================
-- Table: reference.pokemon_evolution_edges
-- Evolution relationships between Pokémon species/forms.
-- ============================================================================
CREATE TABLE reference.pokemon_evolution_edges (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_species_id integer NOT NULL,
    from_form_id integer NOT NULL,
    to_species_id integer NOT NULL,
    to_form_id integer NOT NULL,
    version_group_id integer REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    introduced_generation_id integer NOT NULL REFERENCES reference.generations (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    evolution_method_id integer NOT NULL REFERENCES reference.evolution_methods (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    minimum_level integer,
    item_id integer REFERENCES reference.items (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    held_item_id integer REFERENCES reference.items (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    known_move_id integer REFERENCES reference.moves (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    known_type_id integer REFERENCES reference.types (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    gender text,
    time_of_day text,
    location_label text,
    condition_summary text,
    condition_data jsonb,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT pokemon_evolution_edges_id_positive_check CHECK (id > 0),
    CONSTRAINT pokemon_evolution_edges_from_form_fkey FOREIGN KEY (from_species_id, from_form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_evolution_edges_to_form_fkey FOREIGN KEY (to_species_id, to_form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_evolution_edges_not_self_check CHECK (from_species_id <> to_species_id OR from_form_id <> to_form_id),
    CONSTRAINT pokemon_evolution_edges_minimum_level_check CHECK (minimum_level IS NULL OR minimum_level BETWEEN 1 AND 100),
    CONSTRAINT pokemon_evolution_edges_gender_check CHECK (gender IS NULL OR gender IN ('male', 'female')),
    CONSTRAINT pokemon_evolution_edges_time_of_day_length_check CHECK (time_of_day IS NULL OR CHAR_LENGTH(BTRIM(time_of_day)) BETWEEN 1 AND 80),
    CONSTRAINT pokemon_evolution_edges_location_label_length_check CHECK (location_label IS NULL OR CHAR_LENGTH(BTRIM(location_label)) BETWEEN 1 AND 200),
    CONSTRAINT pokemon_evolution_edges_condition_summary_length_check CHECK (condition_summary IS NULL OR CHAR_LENGTH(BTRIM(condition_summary)) BETWEEN 1 AND 500),
    CONSTRAINT pokemon_evolution_edges_condition_data_object_check CHECK (condition_data IS NULL OR JSONB_TYPEOF(condition_data) = 'object'),
    CONSTRAINT pokemon_evolution_edges_sort_order_positive_check CHECK (sort_order > 0)
);

CREATE UNIQUE INDEX pokemon_evolution_edges_natural_unique ON reference.pokemon_evolution_edges (from_species_id, from_form_id, to_species_id, to_form_id, (COALESCE(version_group_id, 0)), introduced_generation_id, evolution_method_id, (COALESCE(minimum_level, 0)), (COALESCE(item_id, 0)), (COALESCE(held_item_id, 0)), (COALESCE(known_move_id, 0)), (COALESCE(known_type_id, 0)), (COALESCE(gender, '')), (COALESCE(time_of_day, '')), (COALESCE(location_label, '')), (COALESCE(condition_data::text, '{}')));

COMMENT ON INDEX reference.pokemon_evolution_edges_natural_unique IS 'Prevents duplicate evolution edges for the same form pair, scope, method, requirements, and structured mechanic data.';

COMMENT ON COLUMN reference.pokemon_evolution_edges.id IS 'Generated surrogate key for Supabase/client ergonomics; seed files omit id and rely on natural uniqueness constraints.';

COMMENT ON TABLE reference.pokemon_evolution_edges IS 'Version-aware evolution edges between Pokémon species/forms for team evolution actions and planning.';

COMMENT ON COLUMN reference.pokemon_evolution_edges.version_group_id IS 'Nullable when the edge is broadly applicable across version groups.';

COMMENT ON COLUMN reference.pokemon_evolution_edges.condition_data IS 'Structured details for hard-to-model evolution edge cases.';
