-- ============================================================================
-- Table: reference.move_availability
-- Move availability by version group and optional game scope.
-- ============================================================================
CREATE TABLE reference.move_availability (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    move_id integer NOT NULL REFERENCES reference.moves (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    version_group_id integer NOT NULL REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    game_id integer,
    scope_operation text NOT NULL DEFAULT 'add',
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT move_availability_id_positive_check CHECK (id > 0),
    CONSTRAINT move_availability_game_scope_fkey FOREIGN KEY (game_id, version_group_id) REFERENCES reference.game_content_scopes (game_id, version_group_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT move_availability_scope_operation_check CHECK (scope_operation IN ('add', 'override', 'remove'))
);

CREATE UNIQUE INDEX move_availability_vg_unique ON reference.move_availability (move_id, version_group_id)
WHERE
    game_id IS NULL;

CREATE UNIQUE INDEX move_availability_game_unique ON reference.move_availability (move_id, version_group_id, game_id)
WHERE
    game_id IS NOT NULL;

CREATE INDEX move_availability_scope_lookup_idx ON reference.move_availability (version_group_id, game_id);

COMMENT ON INDEX reference.move_availability_vg_unique IS 'Prevents duplicate version-group-wide availability rows for the same move.';

COMMENT ON INDEX reference.move_availability_game_unique IS 'Prevents duplicate game-specific availability rows for the same move.';

COMMENT ON COLUMN reference.move_availability.id IS 'Generated surrogate key for Supabase/client ergonomics; seed files omit id and rely on natural uniqueness constraints.';

COMMENT ON TABLE reference.move_availability IS 'Move availability delta rows for version groups and game-specific exceptions.';

COMMENT ON COLUMN reference.move_availability.game_id IS 'Nullable for version-group-wide availability. When set, the game must be mapped to the same content scope.';

COMMENT ON COLUMN reference.move_availability.scope_operation IS 'Cumulative content-scope operation. add is the normal positive row; override/remove are reserved for source changes that supersede earlier scopes.';
