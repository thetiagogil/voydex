-- ============================================================================
-- Table: reference.pokemon_learnsets
-- Pokémon/form move learnsets by version group and optional game scope.
-- ============================================================================
CREATE TABLE reference.pokemon_learnsets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id integer NOT NULL,
    form_id integer NOT NULL,
    move_id integer NOT NULL REFERENCES reference.moves (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    version_group_id integer NOT NULL REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    game_id integer,
    learn_method_id integer NOT NULL REFERENCES reference.learn_methods (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    level_learned_at integer,
    source_item_id integer REFERENCES reference.items (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    move_machine_id integer REFERENCES reference.move_machines (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    condition_summary text,
    scope_operation text NOT NULL DEFAULT 'add',
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT pokemon_learnsets_id_positive_check CHECK (id > 0),
    CONSTRAINT pokemon_learnsets_form_fkey FOREIGN KEY (species_id, form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_learnsets_game_scope_fkey FOREIGN KEY (game_id, version_group_id) REFERENCES reference.game_content_scopes (game_id, version_group_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_learnsets_level_check CHECK (level_learned_at IS NULL OR level_learned_at BETWEEN 1 AND 100),
    CONSTRAINT pokemon_learnsets_level_method_shape_check CHECK ((learn_method_id = 1 AND level_learned_at IS NOT NULL) OR (learn_method_id <> 1 AND level_learned_at IS NULL)),
    CONSTRAINT pokemon_learnsets_machine_method_shape_check CHECK ((learn_method_id IN (2, 3, 4) AND move_machine_id IS NOT NULL) OR (learn_method_id NOT IN (2, 3, 4) AND move_machine_id IS NULL)),
    CONSTRAINT pokemon_learnsets_condition_summary_length_check CHECK (condition_summary IS NULL OR CHAR_LENGTH(BTRIM(condition_summary)) BETWEEN 1 AND 500),
    CONSTRAINT pokemon_learnsets_scope_operation_check CHECK (scope_operation IN ('add', 'override', 'remove')),
    CONSTRAINT pokemon_learnsets_sort_order_positive_check CHECK (sort_order > 0)
);

CREATE UNIQUE INDEX pokemon_learnsets_vg_unique ON reference.pokemon_learnsets (species_id, form_id, move_id, version_group_id, learn_method_id, (COALESCE(level_learned_at, 0)), (COALESCE(source_item_id, 0)), (COALESCE(move_machine_id, 0)))
WHERE
    game_id IS NULL;

CREATE UNIQUE INDEX pokemon_learnsets_game_unique ON reference.pokemon_learnsets (species_id, form_id, move_id, version_group_id, game_id, learn_method_id, (COALESCE(level_learned_at, 0)), (COALESCE(source_item_id, 0)), (COALESCE(move_machine_id, 0)))
WHERE
    game_id IS NOT NULL;

CREATE INDEX pokemon_learnsets_form_scope_lookup_idx ON reference.pokemon_learnsets (species_id, form_id, version_group_id, game_id, sort_order);

CREATE INDEX pokemon_learnsets_move_scope_lookup_idx ON reference.pokemon_learnsets (move_id, version_group_id, game_id);

CREATE INDEX pokemon_learnsets_method_scope_lookup_idx ON reference.pokemon_learnsets (version_group_id, learn_method_id);

CREATE INDEX pokemon_learnsets_source_item_lookup_idx ON reference.pokemon_learnsets (source_item_id)
WHERE
    source_item_id IS NOT NULL;

CREATE INDEX pokemon_learnsets_move_machine_lookup_idx ON reference.pokemon_learnsets (move_machine_id)
WHERE
    move_machine_id IS NOT NULL;

COMMENT ON INDEX reference.pokemon_learnsets_vg_unique IS 'Prevents duplicate version-group-wide learnset rows while allowing distinct level, item, or machine paths.';

COMMENT ON INDEX reference.pokemon_learnsets_game_unique IS 'Prevents duplicate game-specific learnset rows while allowing distinct level, item, or machine paths.';

COMMENT ON COLUMN reference.pokemon_learnsets.id IS 'Generated surrogate key for Supabase/client ergonomics; seed files omit id and rely on natural uniqueness constraints.';

COMMENT ON TABLE reference.pokemon_learnsets IS 'Source-preserving Pokémon/form move learnset delta rows for games and version groups.';

COMMENT ON COLUMN reference.pokemon_learnsets.level_learned_at IS 'Level for level-up learn rows. Null for non-level methods such as egg, tutor, machine, event, or evolution.';

COMMENT ON COLUMN reference.pokemon_learnsets.move_machine_id IS 'Required for TM/HM/TR learn methods and must reference the matching move machine in the same resolved content-scope closure.';

COMMENT ON COLUMN reference.pokemon_learnsets.scope_operation IS 'Cumulative content-scope operation. add is the normal positive row; override/remove are reserved for source changes that supersede earlier scopes.';
