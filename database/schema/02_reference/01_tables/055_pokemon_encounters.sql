-- ============================================================================
-- Table: reference.pokemon_encounters
-- Where each Pokémon is met: one row per form, place, game and way, with the
-- levels it comes at and, when it only shows some of the time, the
-- condition. A row with no game holds for every version of its
-- group; a version exclusive names its game. A Pokémon handed over (a gift,
-- a trade, a fossil, an Egg, a prize or one you buy) also says who hands it
-- over and, where they apply, what you give for it, its nickname, its held
-- item and its price.
-- ============================================================================
CREATE TABLE reference.pokemon_encounters (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id integer NOT NULL,
    form_id integer NOT NULL,
    location_id integer NOT NULL REFERENCES reference.locations (id) ON UPDATE CASCADE ON DELETE CASCADE,
    version_group_id integer NOT NULL REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    game_id integer,
    encounter_way_id integer NOT NULL REFERENCES reference.encounter_ways (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    level_min integer,
    level_max integer,
    condition text,
    giver text,
    trade_for_species_id integer,
    trade_for_form_id integer,
    nickname text,
    held_item_id integer,
    price text,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT pokemon_encounters_id_positive_check CHECK (id > 0),
    CONSTRAINT pokemon_encounters_form_fkey FOREIGN KEY (species_id, form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT pokemon_encounters_place_fkey FOREIGN KEY (location_id, version_group_id) REFERENCES reference.location_version_groups (location_id, version_group_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT pokemon_encounters_game_scope_fkey FOREIGN KEY (game_id, version_group_id) REFERENCES reference.game_content_scopes (game_id, version_group_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_encounters_condition_length_check CHECK (condition IS NULL OR CHAR_LENGTH(BTRIM(condition)) BETWEEN 1 AND 120),
    CONSTRAINT pokemon_encounters_trade_for_fkey FOREIGN KEY (trade_for_species_id, trade_for_form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_encounters_held_item_fkey FOREIGN KEY (held_item_id) REFERENCES reference.items (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_encounters_trade_for_pair_check CHECK ((trade_for_species_id IS NULL) = (trade_for_form_id IS NULL)),
    CONSTRAINT pokemon_encounters_giver_length_check CHECK (giver IS NULL OR CHAR_LENGTH(BTRIM(giver)) BETWEEN 1 AND 80),
    CONSTRAINT pokemon_encounters_nickname_length_check CHECK (nickname IS NULL OR CHAR_LENGTH(BTRIM(nickname)) BETWEEN 1 AND 12),
    CONSTRAINT pokemon_encounters_price_length_check CHECK (price IS NULL OR CHAR_LENGTH(BTRIM(price)) BETWEEN 1 AND 40),
    CONSTRAINT pokemon_encounters_levels_check CHECK ((level_min IS NULL AND level_max IS NULL) OR (level_min BETWEEN 1 AND 100 AND level_max BETWEEN level_min AND 100))
);

CREATE UNIQUE INDEX pokemon_encounters_group_way_unique ON reference.pokemon_encounters (form_id, location_id, version_group_id, encounter_way_id)
WHERE
    game_id IS NULL;

CREATE UNIQUE INDEX pokemon_encounters_game_way_unique ON reference.pokemon_encounters (form_id, location_id, version_group_id, game_id, encounter_way_id)
WHERE
    game_id IS NOT NULL;

CREATE INDEX pokemon_encounters_species_lookup_idx ON reference.pokemon_encounters (species_id, version_group_id);

CREATE INDEX pokemon_encounters_location_lookup_idx ON reference.pokemon_encounters (location_id, version_group_id);

COMMENT ON TABLE reference.pokemon_encounters IS 'Where each Pokémon is met, one row per form, place, game and way with its level range; no game means every version of the group has it there.';

COMMENT ON COLUMN reference.pokemon_encounters.id IS 'Generated surrogate key; seed files omit it and rely on the natural uniqueness indexes.';

COMMENT ON COLUMN reference.pokemon_encounters.game_id IS 'NULL when every version of the group meets it there the same way; set for a version exclusive or a version-specific level range.';

COMMENT ON COLUMN reference.pokemon_encounters.condition IS 'When it shows, where that is only some of the time: a time of day (Night), a season (Winter), weather (In rain), a swarm (During a swarm) or a weekly event (On Monday nights); for a Pokémon handed over, when or how it is offered (After you get the Thunder Badge); NULL when it is always there.';

COMMENT ON COLUMN reference.pokemon_encounters.giver IS 'Who hands it over: a named character (Bill, Steven) or, when the game leaves them unnamed, who and where in a few words (A boy in the trade house). Only on a Pokémon handed over; NULL where nobody does (an item ball).';

COMMENT ON COLUMN reference.pokemon_encounters.trade_for_form_id IS 'An in-game trade''s ask: the Pokémon you hand over for it, with trade_for_species_id. Only on a trade.';

COMMENT ON COLUMN reference.pokemon_encounters.nickname IS 'The name it comes with, as the game writes it in its own language (MARCEL); NULL when it comes unnamed.';

COMMENT ON COLUMN reference.pokemon_encounters.held_item_id IS 'The item it comes holding; NULL when it holds nothing or the item is not in the item catalogue yet.';

COMMENT ON COLUMN reference.pokemon_encounters.price IS 'What a prize or a Pokémon you buy costs (180 coins, 500 Poké Dollars); only on those two ways.';

COMMENT ON COLUMN reference.pokemon_encounters.level_min IS 'The lowest level it comes at there; NULL with level_max for an in-game trade whose level follows the Pokémon given, or a fixed encounter whose level the source leaves unsaid.';
