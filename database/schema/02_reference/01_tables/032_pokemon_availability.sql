-- ============================================================================
-- Table: reference.pokemon_availability
-- Pokémon/form availability by version group and optional game scope.
-- ============================================================================
CREATE TABLE reference.pokemon_availability (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id integer NOT NULL,
    form_id integer NOT NULL,
    version_group_id integer NOT NULL REFERENCES reference.version_groups (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    game_id integer,
    availability_method_id integer NOT NULL REFERENCES reference.availability_methods (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    scope_operation text NOT NULL DEFAULT 'add',
    notes text,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT pokemon_availability_id_positive_check CHECK (id > 0),
    CONSTRAINT pokemon_availability_form_fkey FOREIGN KEY (species_id, form_id) REFERENCES reference.pokemon_forms (species_id, id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_availability_game_scope_fkey FOREIGN KEY (game_id, version_group_id) REFERENCES reference.game_content_scopes (game_id, version_group_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT pokemon_availability_scope_operation_check CHECK (scope_operation IN ('add', 'override', 'remove')),
    CONSTRAINT pokemon_availability_notes_length_check CHECK (notes IS NULL OR CHAR_LENGTH(BTRIM(notes)) BETWEEN 1 AND 1000)
);

CREATE UNIQUE INDEX pokemon_availability_vg_method_unique ON reference.pokemon_availability (species_id, form_id, version_group_id, availability_method_id)
WHERE
    game_id IS NULL;

CREATE UNIQUE INDEX pokemon_availability_game_method_unique ON reference.pokemon_availability (species_id, form_id, version_group_id, game_id, availability_method_id)
WHERE
    game_id IS NOT NULL;

CREATE INDEX pokemon_availability_scope_lookup_idx ON reference.pokemon_availability (version_group_id, game_id);

CREATE INDEX pokemon_availability_form_lookup_idx ON reference.pokemon_availability (species_id, form_id, version_group_id);

CREATE INDEX pokemon_availability_method_lookup_idx ON reference.pokemon_availability (availability_method_id);

COMMENT ON INDEX reference.pokemon_availability_vg_method_unique IS 'Prevents duplicate version-group-wide availability methods for the same Pokémon form.';

COMMENT ON INDEX reference.pokemon_availability_game_method_unique IS 'Prevents duplicate game-specific availability methods for the same Pokémon form.';

COMMENT ON COLUMN reference.pokemon_availability.id IS 'Generated surrogate key for Supabase/client ergonomics; seed files omit id and rely on natural uniqueness constraints.';

COMMENT ON TABLE reference.pokemon_availability IS 'Pokémon/form availability delta rows for planning, Pokedex filtering, and game-specific warnings.';

COMMENT ON COLUMN reference.pokemon_availability.game_id IS 'Nullable for version-group-wide availability. When set, the game must be mapped to the same content scope.';

COMMENT ON COLUMN reference.pokemon_availability.scope_operation IS 'Cumulative content-scope operation. add is the normal positive row; override/remove are reserved for source changes that supersede earlier scopes.';
