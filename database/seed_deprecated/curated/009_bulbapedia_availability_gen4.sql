INSERT INTO dex.pokemon_availability (species_id, form_id, version_group_id, game_id, is_available, is_version_exclusive, method)
SELECT
  s.id AS species_id,
  COALESCE(f.id, df.id) AS form_id,
  g.version_group_id,
  g.id AS game_id,
  v.is_available::boolean AS is_available,
  v.is_version_exclusive::boolean AS is_version_exclusive,
  v.method::meta.availability_method AS method
FROM v
JOIN dex.pokemon_species s ON s.slug = v.species_slug
LEFT JOIN dex.pokemon_forms f ON f.slug = v.form_slug AND f.species_id = s.id
LEFT JOIN dex.pokemon_forms df ON df.species_id = s.id AND df.is_default = true
JOIN meta.games g ON g.slug = v.game_slug
ON CONFLICT ON CONSTRAINT uq_availability_species_form_per_game DO UPDATE SET
  is_available = EXCLUDED.is_available,
  is_version_exclusive = EXCLUDED.is_version_exclusive,
  method = EXCLUDED.method;

