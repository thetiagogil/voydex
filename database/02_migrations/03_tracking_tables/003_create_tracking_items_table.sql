-- ============================================================================
-- Table: tracking.items
-- Core milestone table. One row = one player-checkable milestone.
-- game_id NULL = applies to all games in the version group.
-- game_id NOT NULL = game-specific milestone.
-- ============================================================================
CREATE TABLE
    tracking.items (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES reference.version_groups (id),
        game_id INTEGER NULL REFERENCES reference.games (id),
        category_id INTEGER NOT NULL REFERENCES tracking.categories (id),
        item_type_id INTEGER NOT NULL REFERENCES tracking.item_types (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        description TEXT NULL,
        sort_order INTEGER NOT NULL,
        is_optional BOOLEAN NOT NULL DEFAULT FALSE,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Comments
COMMENT ON TABLE tracking.items IS 'Core milestone table. One row = one player-checkable milestone. Slugs are unique within (version_group_id, game_id).';

COMMENT ON COLUMN tracking.items.game_id IS 'NULL = milestone applies to all games in the version group. NOT NULL = game-specific milestone.';

COMMENT ON COLUMN tracking.items.sort_order IS 'Display order within the version group and category. Follows game progression, not alphabetical.';