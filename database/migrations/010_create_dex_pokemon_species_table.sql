CREATE TABLE
  dex.pokemon_species (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    national_number INTEGER NOT NULL,
    color VARCHAR(20),
    is_baby BOOLEAN DEFAULT FALSE,
    is_legendary BOOLEAN DEFAULT FALSE,
    is_mythical BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (national_number > 0),
  );

CREATE INDEX idx_pokemon_species_national_number ON dex.pokemon_species (national_number);