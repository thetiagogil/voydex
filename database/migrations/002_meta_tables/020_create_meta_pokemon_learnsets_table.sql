-- =============================================================================
-- POKEMON LEARNSETS TABLE
-- Per-VG move learnsets: which moves each species/form can learn and how
-- =============================================================================
CREATE TYPE meta.learn_method AS ENUM ('level-up', 'tm', 'hm', 'tr', 'egg', 'tutor', 'event', 'reminder');

CREATE TABLE
    meta.pokemon_learnsets (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        species_id INTEGER NOT NULL REFERENCES meta.pokemon_species (id) ON DELETE CASCADE,
        form_id INTEGER NOT NULL REFERENCES meta.pokemon_forms (id) ON DELETE CASCADE,
        move_id INTEGER NOT NULL REFERENCES meta.moves (id) ON DELETE CASCADE,
        version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
        learn_method meta.learn_method NOT NULL,
        level_learned_at INTEGER,
        created_at TIMESTAMP
        WITH
            TIME ZONE DEFAULT NOW (),
            UNIQUE (species_id, form_id, move_id, version_group_id, learn_method),
            -- level_learned_at is required for level-up, must be NULL otherwise
            CHECK (
                (
                    learn_method = 'level-up'
                    AND level_learned_at IS NOT NULL
                    AND level_learned_at >= 0
                )
                OR (
                    learn_method <> 'level-up'
                    AND level_learned_at IS NULL
                )
            )
    );

CREATE INDEX idx_learnsets_species_vg ON meta.pokemon_learnsets (species_id, version_group_id);

CREATE INDEX idx_learnsets_form_vg ON meta.pokemon_learnsets (form_id, version_group_id);

CREATE INDEX idx_learnsets_move_vg ON meta.pokemon_learnsets (move_id, version_group_id);

CREATE INDEX idx_learnsets_vg ON meta.pokemon_learnsets (version_group_id);

CREATE INDEX idx_learnsets_method ON meta.pokemon_learnsets (learn_method);

CREATE INDEX idx_learnsets_species_form_vg ON meta.pokemon_learnsets (species_id, form_id, version_group_id);

COMMENT ON TABLE meta.pokemon_learnsets IS 'Per-VG move learnsets. Estimated 200K-500K rows across all generations. level_learned_at required only for level-up method.';