-- =============================================================================
-- POKEMON AVAILABILITY TABLE
-- Explicit positive model: row exists = species/form is available in this VG
-- =============================================================================
CREATE TYPE meta.availability_method AS ENUM ('catch', 'receive', 'trade', 'evolve', 'evolve-trade', 'breed', 'event', 'transfer', 'other');

CREATE TABLE
    meta.pokemon_availability (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        species_id INTEGER NOT NULL REFERENCES meta.pokemon_species (id) ON DELETE CASCADE,
        form_id INTEGER NOT NULL REFERENCES meta.pokemon_forms (id) ON DELETE CASCADE,
        version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
        game_id INTEGER REFERENCES meta.games (id) ON DELETE CASCADE,
        method meta.availability_method NOT NULL,
        created_at TIMESTAMP
        WITH
            TIME ZONE DEFAULT NOW (),
            -- game_id NULL = available in all games of this VG
            -- game_id set = version-exclusive (e.g. Vulpix only in Blue)
            UNIQUE (species_id, form_id, version_group_id, COALESCE(game_id, 0), method)
    );

CREATE INDEX idx_pokemon_avail_vg ON meta.pokemon_availability (version_group_id);

CREATE INDEX idx_pokemon_avail_species ON meta.pokemon_availability (species_id);

CREATE INDEX idx_pokemon_avail_species_vg ON meta.pokemon_availability (species_id, version_group_id);

CREATE INDEX idx_pokemon_avail_form_vg ON meta.pokemon_availability (form_id, version_group_id);

CREATE INDEX idx_pokemon_avail_game ON meta.pokemon_availability (game_id)
WHERE
    game_id IS NOT NULL;

CREATE INDEX idx_pokemon_avail_method ON meta.pokemon_availability (method);

COMMENT ON TABLE meta.pokemon_availability IS 'Positive availability model: row exists = species/form obtainable in this version group via given method. DLC VG files contain only additions over the base VG.';