CREATE TYPE meta.stat_values AS ENUM ('hp', 'attack', 'defense', 'special-attack', 'special-defense', 'speed');

CREATE TYPE meta.flavor_values AS ENUM ('spicy', 'dry', 'sweet', 'bitter', 'sour');

CREATE TABLE
  meta.natures (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL UNIQUE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    increased_stat meta.stat_values,
    decreased_stat meta.stat_values,
    liked_flavor meta.flavor_values,
    disliked_flavor meta.flavor_values,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (
        (
          increased_stat IS NULL
          AND decreased_stat IS NULL
        )
        OR (
          increased_stat IS NOT NULL
          AND decreased_stat IS NOT NULL
          AND increased_stat <> decreased_stat
        )
      )
  );

-- WHAT: Index on introduced_generation_id (when this nature was first introduced)
-- WHY: Makes it fast to find all natures introduced in a specific generation
-- WHEN USED: "Show me all natures available in Gen 3" (when natures were introduced)
CREATE INDEX idx_natures_introduced_generation ON meta.natures (introduced_generation_id);