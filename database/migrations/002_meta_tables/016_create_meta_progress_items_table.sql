CREATE TABLE
  meta.progress_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,
    progress_category_id INTEGER NOT NULL REFERENCES meta.progress_categories (id) ON DELETE CASCADE,
    game_id INTEGER REFERENCES meta.games (id) ON DELETE CASCADE, -- NULL = default
    description TEXT,
    timeline_message VARCHAR(500),
    location VARCHAR(100),
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW ()
  );

-- WHAT: Index on progress_category_id (which category this item belongs to)
-- WHY: Makes it fast to find all items in a category
-- WHEN USED: "Show me all Gym Badge items"
CREATE INDEX idx_progress_items_category ON meta.progress_items (progress_category_id);

-- WHAT: Index on game_id (which specific game this item is for)
-- WHY: Makes it fast to find game-specific progress items
-- WHEN USED: "Show me progress items unique to Pokemon Red"
CREATE INDEX idx_progress_items_game ON meta.progress_items (game_id);

-- WHAT: Composite index on game + category together
-- WHY: Makes it super fast to filter by BOTH game AND category at once
-- WHEN USED: "Show me all Gym Badge items for Pokemon Red"
CREATE INDEX idx_progress_items_game_category ON meta.progress_items (game_id, progress_category_id);

-- WHAT: Composite index on category + sort_order for ordering
-- WHY: Makes it fast to show items in the correct order within a category
-- WHEN USED: "Show me all Gym Badges in order (Brock's badge → Misty's badge → ...)"
CREATE INDEX idx_progress_items_category_sort ON meta.progress_items (progress_category_id, sort_order);

-- WHAT: Composite index on category + game + sort_order
-- WHY: Makes it fast to fetch progress items filtered by category and game
-- WHEN USED: getPlayProgressItems() - filters by category and optionally by game
CREATE INDEX idx_progress_items_cat_game ON meta.progress_items (progress_category_id, game_id, sort_order);

-- WHAT: Index on slug (URL-friendly identifier)
-- WHY: Makes it fast to find a progress item by its slug
-- WHEN USED: "Find the progress item with slug 'brock-boulder-badge'"
CREATE INDEX idx_progress_items_slug ON meta.progress_items (slug);