CREATE TABLE
  meta.pokemon_species (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    national_number INTEGER NOT NULL,
    color VARCHAR(20),
    is_baby BOOLEAN DEFAULT FALSE,
    is_legendary BOOLEAN DEFAULT FALSE,
    is_mythical BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (national_number > 0)
  );

-- WHAT: Index on national_number (Pokedex number like #001, #025, #150)
-- WHY: Makes it fast to find Pokemon by their Pokedex number
-- WHEN USED: "Show me Pokemon #25" (Pikachu) or sorting by national dex order
CREATE INDEX idx_pokemon_species_national_number ON meta.pokemon_species (national_number);