-- =============================================================================
-- ITEMS TABLE
-- Catalog of all items across all generations
-- =============================================================================
CREATE TYPE meta.item_category AS ENUM ('medicine', 'berries', 'battle', 'held-items', 'key-items', 'machines', 'evolution', 'status', 'stat-boost', 'mail', 'fossils', 'apricorn', 'capture', 'contest', 'miscellaneous');

CREATE TABLE
    meta.items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug VARCHAR(50) NOT NULL UNIQUE,
        name VARCHAR(100) NOT NULL UNIQUE,
        introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
        category meta.item_category NOT NULL,
        description TEXT,
        created_at TIMESTAMP
        WITH
            TIME ZONE DEFAULT NOW ()
    );

CREATE INDEX idx_items_introduced_generation ON meta.items (introduced_generation_id);

CREATE INDEX idx_items_category ON meta.items (category);

CREATE INDEX idx_items_gen_category ON meta.items (introduced_generation_id, category);

COMMENT ON TABLE meta.items IS 'Catalog of all items across all generations (medicines, TMs, held items, key items, etc).';