CREATE TYPE meta.progress_category_type AS ENUM ('main-story', 'post-game', 'side-quest', 'collection', 'dex');

CREATE TABLE
  meta.progress_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
    type meta.progress_category_type NOT NULL DEFAULT 'main-story',
    description TEXT,
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (version_group_id, slug)
  );

-- WHAT: Index on version_group_id (which game version)
-- WHY: Makes it fast to find all progress categories for a game
-- WHEN USED: "Show me all progress categories for Red/Blue"
CREATE INDEX idx_progress_categories_vg ON meta.progress_categories (version_group_id);

-- WHAT: Index on type (main-story, post-game, side-quest, etc.)
-- WHY: Makes it fast to filter categories by type
-- WHEN USED: "Show me only main-story progress" or "Show me post-game content"
CREATE INDEX idx_progress_categories_type ON meta.progress_categories (type);

-- WHAT: Composite index on version_group + type together
-- WHY: Makes it super fast to filter by BOTH game AND category type at once
-- WHEN USED: "Show me main-story progress categories for Red/Blue"
CREATE INDEX idx_progress_categories_vg_type ON meta.progress_categories (version_group_id, type);

-- WHAT: Composite index on version_group + sort_order for ordering
-- WHY: Makes it fast to show categories in the correct order for a game
-- WHEN USED: "Show me all progress categories for Red/Blue in display order"
CREATE INDEX idx_progress_categories_vg_sort ON meta.progress_categories (version_group_id, sort_order);