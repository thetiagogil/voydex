CREATE TABLE
  meta.regional_dex_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id INTEGER NOT NULL REFERENCES meta.pokemon_species (id) ON DELETE CASCADE,
    form_id INTEGER REFERENCES meta.pokemon_forms (id) ON DELETE CASCADE, -- NULL = species/default form
    version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
    regional_number INTEGER NOT NULL,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (version_group_id, regional_number),
      CHECK (regional_number > 0)
  );

-- WHAT: Index on version_group_id (which game version this regional dex belongs to)
-- WHY: Makes it fast to find all Pokemon in a specific regional dex
-- WHEN USED: "Show me all Pokemon in the Kanto Pokedex"
CREATE INDEX idx_regional_dex_vg ON meta.regional_dex_entries (version_group_id);

-- WHAT: Index on species_id (which Pokemon species)
-- WHY: Makes it fast to find which regional dexes include a specific Pokemon
-- WHEN USED: "Which regional dexes include Pikachu?"
CREATE INDEX idx_regional_dex_species ON meta.regional_dex_entries (species_id);

-- WHAT: Index on form_id (which specific form of the Pokemon)
-- WHY: Makes it fast to find regional dex entries for a specific form
-- WHEN USED: "Which regional dexes include Alolan Vulpix form?"
CREATE INDEX idx_regional_dex_form ON meta.regional_dex_entries (form_id);

-- WHAT: Composite index on version_group + regional_number
-- WHY: Makes it fast to look up regional dex entries in order
-- WHEN USED: getPlayRegionalDex() - fetches dex entries and joins with species
CREATE INDEX idx_regional_dex_vg_number ON meta.regional_dex_entries (version_group_id, regional_number);

-- WHAT: Composite index on species + version_group
-- WHY: Makes it fast to look up if a species is in a specific regional dex
-- WHEN USED: Various services that check species availability
CREATE INDEX idx_regional_dex_species_vg ON meta.regional_dex_entries (species_id, version_group_id);