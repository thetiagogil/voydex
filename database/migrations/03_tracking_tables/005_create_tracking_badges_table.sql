-- ============================================================================
-- Table: tracking.badges
-- Badge metadata for tracking milestones.
-- ============================================================================
CREATE TABLE
    tracking.badges (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES reference.version_groups (id),
        game_id INTEGER NULL REFERENCES reference.games (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        sprite_url TEXT NULL,
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Indexes
CREATE INDEX idx_tracking_badges_slug ON tracking.badges (slug);

CREATE INDEX idx_tracking_badges_vg ON tracking.badges (version_group_id);

-- Comments
COMMENT ON TABLE tracking.badges IS 'Badge metadata. Linked to tracking items via item_badge_refs.';