-- ============================================================================
-- Table: tracking.item_decision_options
-- Available options for decision tracking items.
-- Examples: starter Pokémon, fossils, gift Pokémon choices.
-- ============================================================================
CREATE TABLE
    tracking.item_decision_options (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        tracking_item_id INTEGER NOT NULL REFERENCES tracking.items (id) ON DELETE CASCADE,
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        pokemon_species_id INTEGER NULL REFERENCES reference.pokemon_species (id),
        pokemon_form_id INTEGER NULL REFERENCES reference.pokemon_forms (id),
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (tracking_item_id, slug)
    );

-- Indexes
CREATE INDEX idx_tracking_item_decision_options_item ON tracking.item_decision_options (tracking_item_id);

CREATE INDEX idx_tracking_item_decision_options_species ON tracking.item_decision_options (pokemon_species_id)
WHERE
    pokemon_species_id IS NOT NULL;

-- Comments
COMMENT ON TABLE tracking.item_decision_options IS 'Available options for decision tracking items (e.g. starter Pokémon, fossils).';