CREATE TYPE meta.availability_method_type AS ENUM ('catch', 'trade', 'gift', 'event', 'other');

CREATE TABLE
  dex.pokemon_availability (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id INTEGER NOT NULL REFERENCES dex.pokemon_species (id) ON DELETE CASCADE,
    form_id INTEGER REFERENCES dex.pokemon_forms (id) ON DELETE CASCADE, -- NULL = species/default form
    form_id_coalesce INTEGER GENERATED ALWAYS AS (COALESCE(form_id, 0)) STORED,
    version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
    game_id INTEGER NOT NULL REFERENCES meta.games (id) ON DELETE CASCADE,
    is_available BOOLEAN DEFAULT TRUE,
    is_version_exclusive BOOLEAN DEFAULT FALSE,
    method_type meta.availability_method_type DEFAULT 'catch',
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (
        NOT is_version_exclusive
        OR is_available
      )
  );

CREATE INDEX idx_availability_game ON dex.pokemon_availability (game_id);

CREATE INDEX idx_availability_species ON dex.pokemon_availability (species_id);

CREATE INDEX idx_availability_form ON dex.pokemon_availability (form_id);

CREATE INDEX idx_availability_game_species ON dex.pokemon_availability (game_id, species_id);