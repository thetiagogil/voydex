-- ========================================
-- POKEMON SPECIES (identity)
-- ========================================
CREATE TABLE dex.pokemon_species (
  id INTEGER PRIMARY KEY,
  slug VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL UNIQUE,
  introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations(id),
  egg_group1_id INTEGER REFERENCES dex.egg_groups(id),
  egg_group2_id INTEGER REFERENCES dex.egg_groups(id),
  national_number INTEGER NOT NULL,
  color VARCHAR(20),
  gender_rate INTEGER,
  capture_rate INTEGER,
  base_happiness INTEGER,
  growth_rate VARCHAR(20),
  is_baby BOOLEAN DEFAULT false,
  is_legendary BOOLEAN DEFAULT false,
  is_mythical BOOLEAN DEFAULT false,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

  CHECK (national_number > 0),
  CHECK (gender_rate BETWEEN -1 AND 8 OR gender_rate IS NULL),
  CHECK (capture_rate IS NULL OR capture_rate >= 0),
  CHECK (base_happiness IS NULL OR base_happiness >= 0)
);

CREATE INDEX idx_pokemon_species_national_number
  ON dex.pokemon_species(national_number);

-- ========================================
-- POKEMON FORMS (variants that persist outside battle)
-- ========================================
CREATE TABLE dex.pokemon_forms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  species_id INTEGER NOT NULL REFERENCES dex.pokemon_species(id) ON DELETE CASCADE,
  slug VARCHAR(50) NOT NULL,
  name VARCHAR(100) NOT NULL,
  introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations(id),
  height INTEGER,
  weight INTEGER,
  is_default BOOLEAN NOT NULL DEFAULT true,
  sprite_url VARCHAR(255),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE (species_id, slug),

  CHECK (height IS NULL OR height > 0),
  CHECK (weight IS NULL OR weight > 0)
);

CREATE INDEX idx_pokemon_forms_species
  ON dex.pokemon_forms(species_id);

-- exactly one default form per species
CREATE UNIQUE INDEX uq_forms_one_default_per_species
  ON dex.pokemon_forms (species_id)
  WHERE is_default = true;

-- optional: prevent duplicate display names per species
CREATE UNIQUE INDEX uq_forms_species_name
  ON dex.pokemon_forms (species_id, name);

-- ========================================
-- POKEMON ATTRIBUTES (start-only timeline)
-- ========================================
CREATE TABLE dex.pokemon_attributes (
  species_id INTEGER NOT NULL REFERENCES dex.pokemon_species(id) ON DELETE CASCADE,
  form_id INTEGER NOT NULL REFERENCES dex.pokemon_forms(id) ON DELETE CASCADE,
  generation_start_id INTEGER NOT NULL REFERENCES meta.generations(id),
  type1_id INTEGER NOT NULL REFERENCES dex.types(id),
  type2_id INTEGER REFERENCES dex.types(id),
  ability1_id INTEGER REFERENCES dex.abilities(id),
  ability2_id INTEGER REFERENCES dex.abilities(id),
  hidden_ability_id INTEGER REFERENCES dex.abilities(id),
  hp  INTEGER NOT NULL,
  attack INTEGER NOT NULL,
  defense INTEGER NOT NULL,
  special_attack INTEGER,
  special_defense INTEGER,
  speed INTEGER NOT NULL,
  special INTEGER,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  PRIMARY KEY (species_id, form_id, generation_start_id),

  CHECK (type2_id IS NULL OR type1_id <> type2_id),
  CHECK (hp > 0 AND attack > 0 AND defense > 0 AND speed > 0),
  CHECK (special_attack IS NULL OR special_attack > 0),
  CHECK (special_defense IS NULL OR special_defense > 0),
  CHECK (special IS NULL OR special > 0),
  
  -- representation rule: exactly one of (Gen1 single) vs (split)
  -- EITHER: special IS NOT NULL AND spa/spd are BOTH NULL
  -- OR: special IS NULL AND spa/spd are BOTH NOT NULL
  CHECK (
    (special IS NOT NULL AND special_attack IS NULL AND special_defense IS NULL)
    OR
    (special IS NULL AND special_attack IS NOT NULL AND special_defense IS NOT NULL)
  ),

  -- generation rule:
  -- In Gen 1 (generation_start_id = 1): special is allowed (and required by rule above).
  -- In Gen 2+ : special MUST be NULL (split-only).
  CHECK (
    (generation_start_id = 1)
    OR
    (generation_start_id <> 1 AND special IS NULL)
  )  
);

CREATE INDEX idx_pokemon_attrs_lookup
  ON dex.pokemon_attributes (species_id, form_id, generation_start_id DESC);

CREATE INDEX idx_pokemon_attrs_form_gen
  ON dex.pokemon_attributes (form_id, generation_start_id DESC);

-- ========================================
-- FOR CONSISTENCY (attributes cannot start before species/form were introduced)
-- ========================================
CREATE OR REPLACE FUNCTION dex.enforce_pokemon_gen_start()
RETURNS TRIGGER AS $$
DECLARE
  species_intro INT;
  form_intro INT;
BEGIN
  SELECT introduced_generation_id INTO species_intro
  FROM dex.pokemon_species WHERE id = NEW.species_id;

  SELECT introduced_generation_id INTO form_intro
  FROM dex.pokemon_forms WHERE id = NEW.form_id;

  IF NEW.generation_start_id < GREATEST(species_intro, form_intro) THEN
    RAISE EXCEPTION
      'generation_start_id (%) < introduced gen (species %, form %)',
      NEW.generation_start_id, species_intro, form_intro;
  END IF;

  RETURN NEW;
END$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pokemon_attrs_enforce_start ON dex.pokemon_attributes;
CREATE TRIGGER trg_pokemon_attrs_enforce_start
BEFORE INSERT OR UPDATE ON dex.pokemon_attributes
FOR EACH ROW EXECUTE FUNCTION dex.enforce_pokemon_gen_start();
