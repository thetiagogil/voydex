CREATE TABLE
  dex.pokemon_species (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    egg_group1_id INTEGER REFERENCES dex.egg_groups (id),
    egg_group2_id INTEGER REFERENCES dex.egg_groups (id),
    national_number INTEGER NOT NULL,
    color VARCHAR(20),
    gender_rate INTEGER,
    capture_rate INTEGER,
    base_happiness INTEGER,
    growth_rate VARCHAR(20),
    is_baby BOOLEAN DEFAULT FALSE,
    is_legendary BOOLEAN DEFAULT FALSE,
    is_mythical BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (national_number > 0),
      CHECK (
        gender_rate BETWEEN -1 AND 8
        OR gender_rate IS NULL
      ),
      CHECK (
        capture_rate IS NULL
        OR capture_rate >= 0
      ),
      CHECK (
        base_happiness IS NULL
        OR base_happiness >= 0
      )
  );

CREATE INDEX idx_pokemon_species_national_number ON dex.pokemon_species (national_number);