CREATE TYPE dex.stat_values AS ENUM ('hp', 'attack', 'defense', 'special-attack', 'special-defense', 'speed');

CREATE TYPE dex.flavor_values AS ENUM ('spicy', 'dry', 'sweet', 'bitter', 'sour');

CREATE TABLE
  dex.natures (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL UNIQUE,
    generation_introduced_id INTEGER NOT NULL REFERENCES meta.generations (id),
    increased_stat dex.stat_values,
    decreased_stat dex.stat_values,
    liked_flavor dex.flavor_values,
    disliked_flavor dex.flavor_values,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (
        (
          increased_stat IS NULL
          AND decreased_stat IS NULL
        )
        OR (
          increased_stat IS NOT NULL
          AND decreased_stat IS NOT NULL
          AND increased_stat <> decreased_stat
        )
      )
  );

-- WHAT: Index on generation_introduced_id (when this nature was first introduced)
-- WHY: Makes it fast to find all natures introduced in a specific generation
-- WHEN USED: "Show me all natures available in Gen 3" (when natures were introduced)
CREATE INDEX idx_natures_generation_introduced ON dex.natures (generation_introduced_id);