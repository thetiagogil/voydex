CREATE TABLE
  meta.generations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    start_year INTEGER NOT NULL,
    end_year INTEGER,
    new_pokemon_count INTEGER DEFAULT 0,
    total_pokemon_count INTEGER DEFAULT 0,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (id, slug, name)
  );

-- =====================================================
-- Indexes
-- =====================================================
-- WHAT: Index on the slug column (like 'generation-i', 'generation-ii')
-- WHY: Makes it fast to find a generation by its URL-friendly slug
-- WHEN USED: When you visit /generations/generation-i or call API with slug
CREATE INDEX idx_generations_slug ON meta.generations (slug);