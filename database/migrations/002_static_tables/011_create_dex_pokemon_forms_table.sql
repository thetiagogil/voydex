CREATE TABLE
  dex.pokemon_forms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL UNIQUE,
    species_id INTEGER NOT NULL REFERENCES dex.pokemon_species (id) ON DELETE CASCADE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    height INTEGER,
    weight INTEGER,
    is_default BOOLEAN NOT NULL DEFAULT TRUE,
    sprite_url VARCHAR(255),
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (species_id, slug),
      CHECK (
        height IS NULL
        OR height > 0
      ),
      CHECK (
        weight IS NULL
        OR weight > 0
      )
  );

-- WHAT: Index on species_id (which Pokemon species this form belongs to)
-- WHY: Makes it fast to find all forms of a Pokemon
-- WHEN USED: "Show me all forms of Pikachu" (regular, cosplay, partner, etc.)
CREATE INDEX idx_pokemon_forms_species ON dex.pokemon_forms (species_id);

-- WHAT: Unique index ensuring only ONE default form per species (WHERE is_default = TRUE)
-- WHY: Prevents having multiple "default" forms for the same Pokemon
-- WHEN USED: Database enforces this automatically when inserting/updating forms
CREATE UNIQUE INDEX uq_forms_one_default_per_species ON dex.pokemon_forms (species_id)
WHERE
  is_default = TRUE;

-- WHAT: Unique index preventing duplicate form names within the same species
-- WHY: Can't have two forms with the same name for one Pokemon
-- WHEN USED: Database enforces this automatically when inserting/updating forms
CREATE UNIQUE INDEX uq_forms_species_name ON dex.pokemon_forms (species_id, name);