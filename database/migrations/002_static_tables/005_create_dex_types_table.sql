CREATE TABLE
  dex.types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL UNIQUE,
    generation_introduced_id INTEGER NOT NULL REFERENCES meta.generations (id),
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW ()
  );

-- WHAT: Index on generation_introduced_id (when this type was first introduced)
-- WHY: Makes it fast to find all types introduced in a specific generation
-- WHEN USED: "Show me all new types added in Gen 2" (Dark, Steel)
CREATE INDEX idx_types_generation_introduced ON dex.types (generation_introduced_id);