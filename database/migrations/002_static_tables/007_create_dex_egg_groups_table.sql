CREATE TABLE
  dex.egg_groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL UNIQUE,
    generation_introduced_id INTEGER NOT NULL REFERENCES meta.generations (id),
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW ()
  );

-- WHAT: Index on generation_introduced_id (when this egg group was first introduced)
-- WHY: Makes it fast to find all egg groups introduced in a specific generation
-- WHEN USED: "Show me all egg groups available in Gen 1"
CREATE INDEX idx_egg_groups_generation_introduced ON dex.egg_groups (generation_introduced_id);