CREATE TABLE
  dex.abilities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    external_id INTEGER NOT NULL UNIQUE,
    generation_introduced_id INTEGER NOT NULL REFERENCES meta.generations (id),
    effect TEXT,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW ()
  );

-- WHAT: Index on generation_introduced_id (when this ability was first introduced)
-- WHY: Makes it fast to find all abilities introduced in a specific generation
-- WHEN USED: "Show me all new abilities added in Gen 3" (when abilities were introduced)
CREATE INDEX idx_abilities_generation_introduced ON dex.abilities (generation_introduced_id);