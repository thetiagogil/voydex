-- ============================================================================
-- Table: tracking.categories
-- UI grouping for tracking milestones.
-- Examples: main-story, post-game, pokemon, collectibles, choices.
-- ============================================================================
CREATE TABLE
    tracking.categories (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        slug TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW ()
    );

-- Indexes
CREATE INDEX idx_tracking_categories_slug ON tracking.categories (slug);

CREATE INDEX idx_tracking_categories_sort ON tracking.categories (sort_order);

-- Comments
COMMENT ON TABLE tracking.categories IS 'UI grouping categories for tracking milestones.';