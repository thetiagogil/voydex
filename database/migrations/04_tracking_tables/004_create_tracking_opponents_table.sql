-- ============================================================================
-- Table: tracking.opponents
-- Boss/opponent metadata for tracking milestones.
-- ============================================================================
CREATE TABLE
    tracking.opponents (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES reference.version_groups (id),
        game_id INTEGER NULL REFERENCES reference.games (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        opponent_role tracking.opponent_role NOT NULL,
        specialty_type_1_id INTEGER NULL REFERENCES reference.types (id),
        specialty_type_2_id INTEGER NULL REFERENCES reference.types (id),
        sprite_url TEXT NULL,
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Indexes
CREATE INDEX idx_tracking_opponents_slug ON tracking.opponents (slug);

CREATE INDEX idx_tracking_opponents_vg ON tracking.opponents (version_group_id);

CREATE INDEX idx_tracking_opponents_role ON tracking.opponents (opponent_role);

-- Comments
COMMENT ON TABLE tracking.opponents IS 'Boss/opponent metadata. Linked to tracking items via item_opponent_refs.';

COMMENT ON COLUMN tracking.opponents.specialty_type_1_id IS 'Primary specialty/theme type for UI display (e.g. Brock = Rock).';

COMMENT ON COLUMN tracking.opponents.specialty_type_2_id IS 'Secondary specialty/theme type if applicable.';