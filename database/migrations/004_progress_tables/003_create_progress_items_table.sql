-- ============================================================================
-- Table: progress.items
-- Core milestone table. One row = one player-checkable milestone.
-- game_id NULL = applies to all games in the version group.
-- game_id NOT NULL = game-specific milestone.
-- ============================================================================
CREATE TABLE
    progress.items (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id),
        game_id INTEGER NULL REFERENCES meta.games (id),
        category_id INTEGER NOT NULL REFERENCES progress.categories (id),
        item_type_id INTEGER NOT NULL REFERENCES progress.item_types (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        description TEXT NULL,
        sort_order INTEGER NOT NULL,
        is_optional BOOLEAN NOT NULL DEFAULT FALSE,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Indexes
CREATE INDEX idx_progress_items_slug ON progress.items (slug);

CREATE INDEX idx_progress_items_vg ON progress.items (version_group_id);

CREATE INDEX idx_progress_items_game ON progress.items (game_id)
WHERE
    game_id IS NOT NULL;

CREATE INDEX idx_progress_items_category ON progress.items (category_id);

CREATE INDEX idx_progress_items_type ON progress.items (item_type_id);

CREATE INDEX idx_progress_items_vg_category_sort ON progress.items (version_group_id, category_id, sort_order);

-- Comments
COMMENT ON TABLE progress.items IS 'Core milestone table. One row = one player-checkable milestone. Slugs are unique within (version_group_id, game_id).';

COMMENT ON COLUMN progress.items.game_id IS 'NULL = milestone applies to all games in the version group. NOT NULL = game-specific milestone.';

COMMENT ON COLUMN progress.items.sort_order IS 'Display order within the version group and category. Follows game progression, not alphabetical.';