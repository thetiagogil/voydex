-- ============================================================================
-- Table: progress.opponents
-- Boss/opponent metadata for progress milestones.
-- ============================================================================
CREATE TABLE
    progress.opponents (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id),
        game_id INTEGER NULL REFERENCES meta.games (id),
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        opponent_role progress.opponent_role NOT NULL,
        specialty_type_1_id INTEGER NULL REFERENCES meta.types (id),
        specialty_type_2_id INTEGER NULL REFERENCES meta.types (id),
        sprite_url TEXT NULL,
        sort_order INTEGER NOT NULL,
        -- Timestamps
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
        UNIQUE (version_group_id, game_id, slug)
    );

-- Indexes
CREATE INDEX idx_progress_opponents_slug ON progress.opponents (slug);

CREATE INDEX idx_progress_opponents_vg ON progress.opponents (version_group_id);

CREATE INDEX idx_progress_opponents_role ON progress.opponents (opponent_role);

-- Comments
COMMENT ON TABLE progress.opponents IS 'Boss/opponent metadata. Linked to progress items via item_opponent_refs.';

COMMENT ON COLUMN progress.opponents.specialty_type_1_id IS 'Primary specialty/theme type for UI display (e.g. Brock = Rock).';

COMMENT ON COLUMN progress.opponents.specialty_type_2_id IS 'Secondary specialty/theme type if applicable.';