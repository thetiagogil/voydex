SELECT
  s.id AS species_id,
  COALESCE(f.id, df.id) AS form_id,
  GREATEST(v.generation_start_id::integer, COALESCE(f.introduced_generation_id, s.introduced_generation_id))::integer AS generation_start_id,
  t1.id AS type1_id,
  t2.id AS type2_id,
  a1.id AS ability1_id,
  a2.id AS ability2_id,
  ha.id AS hidden_ability_id,
  v.hp::integer,
  v.attack::integer,
  v.defense::integer,
  v.special_attack::integer,
  v.special_defense::integer,
  v.speed::integer,
  v.special::integer
FROM v
JOIN dex.pokemon_species s ON s.slug = v.species_slug
LEFT JOIN dex.pokemon_forms f ON f.slug = v.form_slug AND f.species_id = s.id
LEFT JOIN dex.pokemon_forms df ON df.species_id = s.id AND df.is_default = true
LEFT JOIN dex.types t1 ON t1.slug = v.type1_slug
LEFT JOIN dex.types t2 ON t2.slug = v.type2_slug
LEFT JOIN dex.abilities a1 ON a1.slug = v.ability1_slug
LEFT JOIN dex.abilities a2 ON a2.slug = v.ability2_slug
LEFT JOIN dex.abilities ha ON ha.slug = v.hidden_ability_slug
ON CONFLICT (species_id, form_id, generation_start_id) DO NOTHING;