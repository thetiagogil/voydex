INSERT INTO
    dex.pokemon_availability (species_id, form_id, version_group_id, game_id, is_available, method_type)
SELECT
    ps.id AS species_id,
    pf.id AS form_id,
    vg.id AS version_group_id,
    gam.id AS game_id,
    pav.is_available,
    CAST(
        CASE
        -- external devices/services (+ transfer) ⇒ other
            WHEN pav.method_type IN ('PW', 'DR')
            OR pav.method_type LIKE 'DW%'
            OR pav.method_type = 'TE' THEN 'transfer'
            -- event family (Ev, EV, EvE, EvB…)
            WHEN pav.method_type = 'EV'
            OR pav.method_type LIKE 'Ev%' THEN 'event'
            -- explicit not-in-game
            WHEN pav.method_type IN ('—', '-', '–') THEN 'unobtainable'
            WHEN pav.method_type = 'ET' THEN 'evolve-trade'
            WHEN pav.method_type = 'T' THEN 'trade'
            -- core in-game obtain (catch/receive)
            WHEN pav.method_type IN ('C', 'S', 'D', 'CD', 'DA') THEN 'catch'
            WHEN pav.method_type LIKE 'FS%' THEN 'catch'
            WHEN pav.method_type = 'R' THEN 'receive'
            -- “CC” (communicate) is a modifier: look at suffix
            WHEN pav.method_type LIKE 'CC%' THEN CASE
                WHEN pav.method_type LIKE '%E' THEN 'evolve'
                WHEN pav.method_type LIKE '%B' THEN 'breed'
                WHEN pav.method_type LIKE '%R' THEN 'receive'
                WHEN pav.method_type LIKE '%D' THEN 'catch'
                ELSE 'receive' -- plain CC
            END
            -- generic suffixes (still in-game)
            WHEN pav.method_type LIKE '%E' THEN 'evolve'
            WHEN pav.method_type LIKE '%B' THEN 'breed'
            WHEN pav.method_type LIKE '%R' THEN 'receive'
            ELSE 'other'
        END AS meta.availability_method_type
    ) AS method_type
FROM
    pav
    JOIN dex.pokemon_species ps ON ps.slug = pav.species_slug
    LEFT JOIN dex.pokemon_forms pf ON pf.slug = pav.form_slug
    JOIN meta.version_groups vg ON vg.slug = pav.version_group_slug
    LEFT JOIN meta.games gam ON gam.slug = pav.game_slug ON CONFLICT DO NOTHING;