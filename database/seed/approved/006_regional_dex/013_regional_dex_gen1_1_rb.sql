    rd
    JOIN dex.pokemon_species ps ON ps.slug = rd.species_slug
    LEFT JOIN dex.pokemon_forms pf ON pf.slug = rd.form_slug
    JOIN meta.version_groups vg ON vg.slug = rd.version_group_slug ON CONFLICT DO NOTHING;