#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { databaseDir, rootDir, supabaseDir } from "./context.mjs";
import { collectSqlFiles, relativePath } from "./files.mjs";

const migrationsDir = path.join(supabaseDir, "migrations");
const schemaMigrationPath = path.join(
  migrationsDir,
  "00000000000000_voydex_current_schema.sql",
);
const seedPath = path.join(supabaseDir, "seed.sql");
const schemaRoot = path.join(databaseDir, "schema");
const seedsRoot = path.join(databaseDir, "seeds");
const checkOnly = process.argv.slice(2).includes("--check");

if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  console.error(
    "Usage: node scripts/database/build-local-artifacts.mjs [--check]",
  );
  process.exit(1);
}

function toRelativePath(filePath) {
  return relativePath(rootDir, filePath);
}

function readSqlFile(filePath) {
  const fileContents = fs.readFileSync(filePath, "utf8").trimEnd();

  return [
    "-- ============================================================================",
    `-- Source: ${toRelativePath(filePath)}`,
    "-- ============================================================================",
    fileContents,
    "",
  ].join("\n");
}

function buildSqlArtifact(title, description, sqlFiles) {
  return [
    "-- ============================================================================",
    `-- ${title}`,
    "-- ============================================================================",
    "-- Generated by scripts/database/build-local-artifacts.mjs. Do not edit by hand.",
    `-- ${description}`,
    "-- ============================================================================",
    "",
    ...sqlFiles.map(readSqlFile),
    "",
  ].join("\n");
}

const schemaFiles = collectSqlFiles(schemaRoot).sort((a, b) =>
  toRelativePath(a).localeCompare(toRelativePath(b)),
);
const seedFiles = collectSqlFiles(seedsRoot).sort((a, b) =>
  toRelativePath(a).localeCompare(toRelativePath(b)),
);

const artifacts = [
  {
    contents: buildSqlArtifact(
      "Voydex Local Supabase Schema Entrypoint",
      "This file loads the clean Voydex schema for local Supabase resets.",
      schemaFiles,
    ),
    fileCount: schemaFiles.length,
    filePath: schemaMigrationPath,
    requiredInCheck: true,
    sourceLabel: "schema",
  },
  {
    contents: buildSqlArtifact(
      "Voydex Local Supabase Seed Entrypoint",
      "This file loads deterministic Voydex seed data after migrations.",
      seedFiles,
    ),
    fileCount: seedFiles.length,
    filePath: seedPath,
    requiredInCheck: false,
    sourceLabel: "seed",
  },
];

if (checkOnly) {
  const staleArtifacts = artifacts.filter(
    ({ contents, filePath, requiredInCheck }) =>
      (requiredInCheck && !fs.existsSync(filePath)) ||
      (fs.existsSync(filePath) &&
        fs.readFileSync(filePath, "utf8") !== contents),
  );

  if (staleArtifacts.length > 0) {
    for (const { filePath } of staleArtifacts) {
      console.error(`Generated artifact is stale: ${toRelativePath(filePath)}`);
    }

    console.error("Run `npm run db:artifacts:build` to regenerate it.");
    process.exit(1);
  }

  for (const { fileCount, filePath, sourceLabel } of artifacts) {
    if (!fs.existsSync(filePath)) {
      console.log(
        `Skipped absent ignored artifact ${toRelativePath(filePath)}; ${fileCount} ${sourceLabel} files are covered by source audits.`,
      );
      continue;
    }

    console.log(
      `Verified ${toRelativePath(filePath)} against ${fileCount} ${sourceLabel} files.`,
    );
  }
} else {
  fs.mkdirSync(migrationsDir, { recursive: true });

  for (const { contents, fileCount, filePath, sourceLabel } of artifacts) {
    fs.writeFileSync(filePath, contents, "utf8");
    console.log(
      `Wrote ${toRelativePath(filePath)} from ${fileCount} ${sourceLabel} files.`,
    );
  }
}
