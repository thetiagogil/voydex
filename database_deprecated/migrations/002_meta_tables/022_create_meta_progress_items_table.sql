-- =============================================================================
-- PROGRESS ITEMS TABLE
-- Individual progress milestones within categories
-- =============================================================================
CREATE TYPE meta.tracking_type AS ENUM ('boolean', 'counter');

CREATE TABLE
    meta.progress_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug VARCHAR(100) NOT NULL,
        name VARCHAR(200) NOT NULL,
        progress_category_id INTEGER NOT NULL REFERENCES meta.progress_categories (id) ON DELETE CASCADE,
        game_id INTEGER REFERENCES meta.games (id) ON DELETE CASCADE,
        description TEXT,
        timeline_message VARCHAR(500),
        location VARCHAR(100),
        sort_order INTEGER NOT NULL,
        tracking_type meta.tracking_type NOT NULL DEFAULT 'boolean',
        target_count INTEGER,
        created_at TIMESTAMP
        WITH
            TIME ZONE DEFAULT NOW (),
            -- target_count required for counter items, must be NULL for boolean
            CHECK (
                (
                    tracking_type = 'counter'
                    AND target_count IS NOT NULL
                    AND target_count > 0
                )
                OR (
                    tracking_type = 'boolean'
                    AND target_count IS NULL
                )
            )
    );

CREATE INDEX idx_progress_items_category ON meta.progress_items (progress_category_id);

CREATE INDEX idx_progress_items_game ON meta.progress_items (game_id);

CREATE INDEX idx_progress_items_game_category ON meta.progress_items (game_id, progress_category_id);

CREATE INDEX idx_progress_items_category_sort ON meta.progress_items (progress_category_id, sort_order);

CREATE INDEX idx_progress_items_cat_game ON meta.progress_items (progress_category_id, game_id, sort_order);

CREATE INDEX idx_progress_items_slug ON meta.progress_items (slug);

COMMENT ON TABLE meta.progress_items IS 'Individual progress milestones. tracking_type=boolean for simple completion, counter for collectibles (e.g. 50 Zygarde Cells). game_id NULL = shared across all games in the VG.';