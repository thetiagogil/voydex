CREATE TABLE
  meta.pokemon_species (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    introduced_generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    national_number INTEGER NOT NULL,
    color VARCHAR(20),
    is_baby BOOLEAN DEFAULT FALSE,
    is_legendary BOOLEAN DEFAULT FALSE,
    is_mythical BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      CHECK (national_number > 0)
  );

-- WHAT: Index on national_number (Pokedex number like #001, #025, #150)
-- WHY: Makes it fast to find Pokemon by their Pokedex number
-- WHEN USED: "Show me Pokemon #25" (Pikachu) or sorting by national dex order
CREATE INDEX idx_pokemon_species_national_number ON meta.pokemon_species (national_number);

-- WHAT: Partial index on mythical Pokemon
-- WHY: Makes it fast to filter mythical Pokemon when calculating dex completion
-- WHEN USED: getPlayProgressCategories() when filtering mythical Pokemon
CREATE INDEX idx_species_mythical ON meta.pokemon_species (id) WHERE is_mythical = TRUE;

-- WHAT: Partial index on legendary Pokemon
-- WHY: Makes it fast to filter legendary Pokemon
-- WHEN USED: Filtering legendary Pokemon for various features
CREATE INDEX idx_species_legendary ON meta.pokemon_species (id) WHERE is_legendary = TRUE;