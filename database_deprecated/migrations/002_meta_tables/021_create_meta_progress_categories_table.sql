-- =============================================================================
-- PROGRESS CATEGORIES TABLE
-- Categories of progress milestones per version group
-- =============================================================================
CREATE TYPE meta.progress_category_type AS ENUM ('main-story', 'post-game', 'side-quest', 'species-goal', 'collectible');

CREATE TABLE
    meta.progress_categories (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug VARCHAR(50) NOT NULL,
        name VARCHAR(100) NOT NULL,
        version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
        type meta.progress_category_type NOT NULL DEFAULT 'main-story',
        description TEXT,
        sort_order INTEGER NOT NULL,
        created_at TIMESTAMP
        WITH
            TIME ZONE DEFAULT NOW (),
            UNIQUE (version_group_id, slug)
    );

CREATE INDEX idx_progress_categories_vg ON meta.progress_categories (version_group_id);

CREATE INDEX idx_progress_categories_type ON meta.progress_categories (type);

CREATE INDEX idx_progress_categories_vg_type ON meta.progress_categories (version_group_id, type);

CREATE INDEX idx_progress_categories_vg_sort ON meta.progress_categories (version_group_id, sort_order);

COMMENT ON TABLE meta.progress_categories IS 'Progress milestone categories per version group. Legendaries are modeled as species-goal categories, not a separate enum value.';