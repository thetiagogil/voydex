CREATE TABLE
  meta.games (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    generation_id INTEGER NOT NULL REFERENCES meta.generations (id),
    region_id INTEGER NOT NULL REFERENCES meta.regions (id),
    version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id),
    type_id INTEGER NOT NULL REFERENCES meta.game_types (id),
    regional_dex_count INTEGER,
    national_dex_count INTEGER,
    release_year INTEGER NOT NULL CHECK (release_year BETWEEN 1996 AND 2100),
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW (),
      UNIQUE (version_group_id, name)
  );

-- WHAT: Index on generation_id (foreign key)
-- WHY: Makes it fast to find all games in a generation
-- WHEN USED: "Show me all Gen 1 games"
CREATE INDEX idx_games_generation ON meta.games (generation_id);

-- WHAT: Index on region_id (foreign key)
-- WHY: Makes it fast to find all games in a region
-- WHEN USED: "Show me all Kanto games"
CREATE INDEX idx_games_region ON meta.games (region_id);

-- WHAT: Index on version_group_id (foreign key)
-- WHY: Makes it fast to find all games in a version group
-- WHEN USED: "Show me all games in Red/Blue version group"
CREATE INDEX idx_games_version_group ON meta.games (version_group_id);

-- WHAT: Index on type_id (foreign key to game_types)
-- WHY: Makes it fast to filter games by type
-- WHEN USED: "Show me only main-series games" or "Show me only remakes"
CREATE INDEX idx_games_type ON meta.games (type_id);

-- WHAT: Composite index on generation + type together
-- WHY: Makes it super fast to filter by BOTH generation AND type at once
-- WHEN USED: "Show me main-series games in Gen 1"
CREATE INDEX idx_games_generation_type ON meta.games (generation_id, type_id);

-- WHAT: Index on release_year sorted newest first (DESC)
-- WHY: Makes it fast to sort games by release date
-- WHEN USED: "Show me games sorted by release year"
CREATE INDEX idx_games_release_year ON meta.games (release_year DESC);

-- WHAT: Composite index on generation + version_group
-- WHY: Makes it fast to look up games by generation with version group info
-- WHEN USED: Many services that need game details with version group
CREATE INDEX idx_games_gen_vg ON meta.games (generation_id, version_group_id);