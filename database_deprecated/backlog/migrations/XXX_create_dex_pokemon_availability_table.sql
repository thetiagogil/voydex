CREATE TYPE meta.availability_method_type AS ENUM ('catch', 'receive', 'trade', 'evolve', 'evolve-trade', 'breed', 'event', 'transfer', 'other', 'unobtainable');

CREATE TABLE
  meta.pokemon_availability (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id INTEGER NOT NULL REFERENCES meta.pokemon_species (id) ON DELETE CASCADE,
    form_id INTEGER REFERENCES meta.pokemon_forms (id) ON DELETE CASCADE, -- NULL = default form
    version_group_id INTEGER NOT NULL REFERENCES meta.version_groups (id) ON DELETE CASCADE,
    game_id INTEGER REFERENCES meta.games (id) ON DELETE CASCADE, -- NULL = VG-wide row
    is_available BOOLEAN DEFAULT TRUE,
    method_type meta.availability_method_type DEFAULT 'catch',
    created_at TIMESTAMP
    WITH
      TIME ZONE DEFAULT NOW ()
  );

CREATE INDEX idx_availability_game ON meta.pokemon_availability (game_id);

CREATE INDEX idx_availability_species ON meta.pokemon_availability (species_id);

CREATE INDEX idx_availability_form ON meta.pokemon_availability (form_id);

CREATE INDEX idx_availability_vg ON meta.pokemon_availability (version_group_id);

CREATE INDEX idx_availability_game_species ON meta.pokemon_availability (game_id, species_id);

-- (nice-to-have) fast lookups for species within a VG or game
CREATE INDEX idx_availability_species_vg ON meta.pokemon_availability (species_id, version_group_id);

CREATE INDEX idx_availability_species_game ON meta.pokemon_availability (species_id, game_id);